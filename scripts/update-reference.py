#!/usr/bin/env python3
"""Generate docs/reference.md from capellactl/config/schema.json (CAP-033 AC3). `make docs` runs this.

Usage: python scripts/update-reference.py [--check]

--check exits 1 when the committed file differs from what the schema produces (CI).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from capellactl.cli.help import MUTABILITY, schema_fields  # noqa: E402

OUT = ROOT / "docs" / "reference.md"
CHANGES = {"updatable": "updatable", "immutable": "**immutable**", "key": "key", "replace": "re-created",
           "rotate-only": "rotate only", "tool": "capellactl only"}


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _type(path: str, node: dict[str, Any]) -> str:
    t = node.get("type")
    if not t and node.get("oneOf"):
        t = " or ".join(sorted({str(o.get("type", "")) for o in node["oneOf"] if o.get("type")}))
    if t == "array":
        items = node.get("items") or {}
        if items.get("type") == "object":
            return "list of objects"
        t = f"list of {items.get('type', 'values')}"
    enum = node.get("enum") or (node.get("items") or {}).get("enum")
    if enum and len(enum) > 12:  # timezones: a few examples, the full list offline
        t = f"{t}: " + ", ".join(f"`{e}`" for e in enum[:4]) + f" … ({len(enum)} values: `capellactl help config {path}`)"
    elif enum:
        t = f"{t}: " + ", ".join(f"`{e}`" for e in enum)
    if "minimum" in node or "maximum" in node:
        t += f" ({node.get('minimum', '…')}–{node.get('maximum', '…')})"
    return str(t or "value")


def _default(node: dict[str, Any]) -> str:
    if "default" not in node:
        return ""
    d = node["default"]
    return f"`{str(d).lower() if isinstance(d, bool) else d}`"


def _is_section(node: dict[str, Any]) -> bool:
    if node.get("type") == "object" and node.get("properties"):
        return True
    items = node.get("items") or {}
    return node.get("type") == "array" and isinstance(items, dict) and items.get("type") == "object"


def render() -> str:
    fields = schema_fields()
    sections: dict[str, list[tuple[str, dict[str, Any]]]] = {"(top level)": []}
    for path, node in fields.items():
        if _is_section(node) and "." not in path and path not in sections:
            sections.setdefault(path, [])
    for path, node in fields.items():
        parent = path.rsplit(".", 1)[0] if "." in path else "(top level)"
        while parent not in sections and "." in parent:  # nested objects are listed in their nearest section
            parent = parent.rsplit(".", 1)[0]
        if _is_section(node) and node.get("type") == "array":
            sections.setdefault(path, [])
            if "." in path:
                sections[path.rsplit(".", 1)[0] if path.rsplit(".", 1)[0] in sections else parent].append((path, node))
            else:
                sections["(top level)"].append((path, node))
            continue
        sections.setdefault(parent, []).append((path, node))

    lines = [
        "# capella.yaml reference",
        "",
        "<!-- Generated by scripts/update-reference.py from capellactl/config/schema.json; do not edit by hand. "
        "Run `make docs`. -->",
        "",
        "Every field capellactl reads from `capella.yaml`, generated from the schema that `capellactl validate` uses. "
        "The same details are shown offline by `capellactl help config FIELD` (for example "
        "`capellactl help config projects.clusters.deletionProtection`).",
        "",
        "**Changes** says what happens when the value is changed in the file and applied:",
        "",
    ]
    lines += [f"- **{CHANGES[k].strip('*')}**: {v}" for k, v in MUTABILITY.items()]
    lines += ["", "The single-project form (`project:` and `clusters:` at the top level) uses the same fields as "
              "`projects[].…`; `capellactl help config` maps one to the other.", ""]
    for section, rows in sections.items():
        if not rows:
            continue
        lines += [f"## {section}", ""]
        node = fields.get(section)
        if node and node.get("description"):
            lines += [_cell(node["description"]), ""]
        lines += ["| Field | Type | Default | Changes | API | Description |", "|---|---|---|---|---|---|"]
        for path, n in rows:
            name = path[len(section) + 1:] if path.startswith(section + ".") else path
            lines.append(f"| `{name}` | {_cell(_type(path, n))} | {_default(n)} | "
                         f"{CHANGES.get(n.get('x-mutability', ''), '')} | {_cell(n.get('x-api', ''))} | "
                         f"{_cell(n.get('description', ''))} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/reference.md is out of date: run 'python3 scripts/update-reference.py' (or 'make docs') and "
                  "commit the result", file=sys.stderr)
            return 1
        print("docs/reference.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"written: {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
