#!/usr/bin/env python3
"""Generate and check THIRD_PARTY_NOTICES.md and the dependency licence policy (CAP-044).

    python scripts/third-party-notices.py            # regenerate (needs network for packages not installed here)
    python scripts/third-party-notices.py --check    # offline: fail when the file is stale or a licence is not allowed

The dependency graph starts at capellactl's runtime requirements. Platform and Python-version markers are
ignored when generating, so packages needed only on Linux, Windows or older Pythons are listed too;
their metadata comes from the installed package or, if it is not installed here, from PyPI.
`--check` looks at what is installed on this machine (CI runs it on every OS and Python version) and fails
when an installed runtime dependency is missing from the file, has a different licence, or has a licence
outside scripts/licence-policy.json.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from dataclasses import dataclass
from importlib import metadata
from pathlib import Path
from typing import Any

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
NOTICES = ROOT / "THIRD_PARTY_NOTICES.md"
POLICY = ROOT / "scripts" / "licence-policy.json"
PROJECT = "capellactl"

# Free-text licence names and trove classifiers → SPDX ids.
ALIASES = {
    "mit": "MIT", "mit license": "MIT", "apache 2.0": "Apache-2.0", "apache-2.0": "Apache-2.0",
    "apache license 2.0": "Apache-2.0", "apache software license": "Apache-2.0", "apache license, version 2.0":
    "Apache-2.0", "bsd": "BSD-3-Clause", "bsd license": "BSD-3-Clause", "bsd-3-clause": "BSD-3-Clause",
    "bsd-2-clause": "BSD-2-Clause", "isc": "ISC", "isc license (iscl)": "ISC", "mpl-2.0": "MPL-2.0",
    "mozilla public license 2.0 (mpl 2.0)": "MPL-2.0", "python software foundation license": "PSF-2.0",
    "psf-2.0": "PSF-2.0", "the unlicense (unlicense)": "Unlicense",
}
HEADER = """# Third-party notices

capellactl (Apache-2.0, see LICENSE and NOTICE) depends on the open-source packages below, which are
distributed under their own licences. Generated by `scripts/third-party-notices.py` (`make notices`); do
not edit by hand. "Needed" shows the condition from the requirement when a package is only installed on
some platforms or Python versions.

| Package | Version | Licence | Needed | Project |
|---|---|---|---|---|
"""
ROW = re.compile(r"^\| (?P<name>[^|]+?) \| (?P<version>[^|]*?) \| (?P<licence>[^|]+?) \| (?P<needed>[^|]*?) \| (?P<url>[^|]*?) \|$")


@dataclass
class Dep:
    name: str
    version: str
    licence: str
    needed: str
    url: str

    def row(self) -> str:
        return f"| {self.name} | {self.version} | {self.licence} | {self.needed} | {self.url} |"


# ------------------------------------------------------------------ licences
def normalize(text: str | None) -> str | None:
    if not text:
        return None
    t = text.strip()
    if "\n" in t or len(t) > 80:  # a full licence text, not a name
        return None
    return ALIASES.get(t.lower(), t)


def licence_from(expression: str | None, free_text: str | None, classifiers: list[str]) -> str:
    """SPDX expression from package metadata: License-Expression, else License, else the trove classifiers."""
    if expression:
        return expression.strip()
    named = normalize(free_text)
    if named:
        return named
    ids = [ALIASES.get(c.split(" :: ")[-1].lower()) for c in classifiers if c.startswith("License ::")]
    ids = [i for i in ids if i]
    return " OR ".join(dict.fromkeys(ids)) if ids else "UNKNOWN"


def allowed(expression: str, policy: set[str]) -> bool:
    """True when an SPDX expression can be satisfied with allowed licences (OR: any side, AND: both sides)."""
    expr = expression.strip()
    while expr.startswith("(") and expr.endswith(")") and _balanced(expr[1:-1]):
        expr = expr[1:-1].strip()
    for op, combine in ((" OR ", any), (" AND ", all)):
        parts = _split_top(expr, op)
        if len(parts) > 1:
            return combine(allowed(p, policy) for p in parts)
    return expr.split(" WITH ")[0].strip() in policy


def _balanced(s: str) -> bool:
    depth = 0
    for ch in s:
        depth += {"(": 1, ")": -1}.get(ch, 0)
        if depth < 0:
            return False
    return depth == 0


def _split_top(expr: str, op: str) -> list[str]:
    parts, depth, start, i = [], 0, 0, 0
    while i < len(expr):
        ch = expr[i]
        depth += {"(": 1, ")": -1}.get(ch, 0)
        if depth == 0 and expr.startswith(op, i):
            parts.append(expr[start:i])
            start = i + len(op)
            i = start
            continue
        i += 1
    parts.append(expr[start:])
    return [p.strip() for p in parts]


def load_policy() -> set[str]:
    return set(json.loads(POLICY.read_text(encoding="utf-8"))["allowed"])


# ------------------------------------------------------------------ metadata
URL_LABELS = ("homepage", "home", "source", "source code", "repository", "github", "documentation")


def _project_url(home: str | None, labelled: dict[str, str]) -> str:
    """Home page, else the Homepage/Source/Repository project URL, else any project URL."""
    if home:
        return home
    by_label = {k.strip().lower(): v.strip() for k, v in labelled.items()}
    for label in URL_LABELS:
        if by_label.get(label):
            return by_label[label]
    return next(iter(by_label.values()), "")


def _installed(name: str) -> dict[str, Any] | None:
    try:
        m = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return None
    labelled = dict(u.split(",", 1) for u in m.get_all("Project-URL") or [] if "," in u)
    return {"name": m["Name"], "version": m["Version"], "licence": licence_from(
        m.get("License-Expression"), m.get("License"), m.get_all("Classifier") or []),
        "url": _project_url(m.get("Home-page"), labelled), "requires": m.get_all("Requires-Dist") or []}


def _pypi(name: str) -> dict[str, Any]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/json", timeout=30) as r:  # noqa: S310 - fixed host
        info = json.load(r)["info"]
    return {"name": info["name"], "version": info["version"], "licence": licence_from(
        info.get("license_expression"), info.get("license"), info.get("classifiers") or []),
        "url": _project_url(info.get("home_page"), info.get("project_urls") or {}),
        "requires": info.get("requires_dist") or []}


def _condition(req: Requirement) -> str | None:
    """'' when always needed, the marker text when platform/Python-specific, None when only for an extra."""
    if req.marker is None:
        return ""
    text = str(req.marker)
    if "extra" in text:
        return None
    return text


def collect(offline: bool) -> list[Dep]:
    """Every runtime dependency of capellactl, on every platform and supported Python version."""
    root = _installed(PROJECT)
    if root is None:
        raise SystemExit(f"{PROJECT} is not installed in this environment; run: pip install -e '.[dev]'")
    found: dict[str, Dep] = {}
    queue: list[tuple[str, str]] = []
    for r in root["requires"]:
        req = Requirement(r)
        cond = _condition(req)
        if cond is not None:
            queue.append((req.name, cond))
    while queue:
        name, cond = queue.pop(0)
        key = canonicalize_name(name)
        if key in found:
            if found[key].needed and not cond:
                found[key].needed = ""  # needed unconditionally through another path
            continue
        meta = _installed(name)
        if meta is None:
            if offline:
                continue
            meta = _pypi(name)
        found[key] = Dep(meta["name"], meta["version"], meta["licence"], cond, meta["url"])
        for r in meta["requires"]:
            req = Requirement(r)
            sub = _condition(req)
            if sub is not None:
                queue.append((req.name, " and ".join(c for c in (cond, sub) if c)))
    return sorted(found.values(), key=lambda d: canonicalize_name(d.name))


def render(deps: list[Dep]) -> str:
    return HEADER + "\n".join(d.row() for d in deps) + "\n"


def parse(text: str) -> dict[str, Dep]:
    rows = {}
    for line in text.splitlines():
        m = ROW.match(line)
        if m and m["name"] not in ("Package", "---"):
            rows[canonicalize_name(m["name"])] = Dep(m["name"], m["version"], m["licence"], m["needed"], m["url"])
    return rows


# ------------------------------------------------------------------ check
def check(text: str, installed: list[Dep], policy: set[str]) -> list[str]:
    """Problems for the dependencies installed here: missing from the file, licence changed, or not allowed."""
    listed = parse(text)
    problems = []
    for d in installed:
        row = listed.get(canonicalize_name(d.name))
        if row is None:
            problems.append(f"{d.name} {d.version} ({d.licence}) is not in THIRD_PARTY_NOTICES.md")
        elif row.licence != d.licence:
            problems.append(f"{d.name}: THIRD_PARTY_NOTICES.md says {row.licence}, the package says {d.licence}")
        if not allowed(d.licence, policy):
            problems.append(f"{d.name} {d.version} is licensed {d.licence}, which is not allowed by "
                            "scripts/licence-policy.json")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when the file is stale or a licence is not allowed")
    args = ap.parse_args(argv)
    policy = load_policy()
    if args.check:
        text = NOTICES.read_text(encoding="utf-8") if NOTICES.exists() else ""
        problems = check(text, collect(offline=True), policy)
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        if problems:
            print("Fix the dependency or run 'make notices' to regenerate THIRD_PARTY_NOTICES.md.", file=sys.stderr)
            return 1
        print("THIRD_PARTY_NOTICES.md is up to date; every dependency licence is allowed")
        return 0
    deps = collect(offline=False)
    bad = [d for d in deps if not allowed(d.licence, policy)]
    NOTICES.write_text(render(deps), encoding="utf-8")
    print(f"THIRD_PARTY_NOTICES.md updated: {len(deps)} packages")
    for d in bad:
        print(f"error: {d.name} {d.version} is licensed {d.licence}, which is not allowed", file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
